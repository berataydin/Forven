import { describe, it, expect } from 'vitest';
import {
  SETTINGS_MANIFEST,
  SETTINGS_AREAS,
  SETTINGS_SUBSECTIONS,
  BACKEND_DEFAULTS,
  BACKEND_DEFAULTS_APPLIED,
  applyBackendDefaults,
  type SettingsEntry,
} from '$lib/settings/manifest';

describe('settings manifest invariants', () => {
  it('every entry has a description', () => {
    for (const e of SETTINGS_MANIFEST) {
      expect(e.description.trim().length, `missing description on ${e.id}`).toBeGreaterThan(0);
    }
  });

  it('every entry has a non-undefined default', () => {
    for (const e of SETTINGS_MANIFEST) {
      expect(e.default, `missing default on ${e.id}`).not.toBeUndefined();
    }
  });

  it('every entry lists a valid area', () => {
    const areas = new Set(SETTINGS_AREAS.map((a) => a.id));
    for (const e of SETTINGS_MANIFEST) {
      expect(areas.has(e.area), `${e.id} -> area ${e.area}`).toBe(true);
    }
  });

  it('every entry lists an existing subsection in its area', () => {
    const pairs = new Set(SETTINGS_SUBSECTIONS.map((s) => `${s.area}/${s.id}`));
    for (const e of SETTINGS_MANIFEST) {
      expect(pairs.has(`${e.area}/${e.subsection}`), `${e.id}`).toBe(true);
    }
  });

  it('every entry has a non-empty usedBy', () => {
    for (const e of SETTINGS_MANIFEST) {
      expect(e.usedBy.length, `${e.id}`).toBeGreaterThan(0);
    }
  });

  it('ids are unique', () => {
    const seen = new Set<string>();
    for (const e of SETTINGS_MANIFEST) {
      expect(seen.has(e.id), `duplicate ${e.id}`).toBe(false);
      seen.add(e.id);
    }
  });

  it('SETTINGS_AREAS has Home first and Danger Zone last', () => {
    expect(SETTINGS_AREAS[0].id).toBe('home');
    expect(SETTINGS_AREAS[SETTINGS_AREAS.length - 1].id).toBe('danger');
  });

  it('Danger Zone is flagged danger: true', () => {
    const danger = SETTINGS_AREAS.find((a) => a.id === 'danger');
    expect(danger?.danger).toBe(true);
  });
});

// ARCH-05: these suites used to pin each default to a number typed out here as
// well as in manifest.ts as well as in the engine — three copies of one value,
// and the copies drifted. `quick_screen.min_profit_factor` was pinned at 1.05
// while the engine's Default preset had relaxed to 1.0, so this file was
// actively holding a stale caption in place on the page an operator reviews
// before arming live capital. They now assert AGREEMENT with the backend map
// (backendDefaults.generated.json, regenerated by
// `python -m forven.settings_manifest`); what is pinned is that the knob exists,
// is wired to the right path, and carries the engine's own number.
function assertPipelineKnob(id: string, backendPath: string): SettingsEntry {
  const entry = SETTINGS_MANIFEST.find((e) => e.id === id);
  expect(entry, `${id} missing from manifest`).toBeDefined();
  expect(entry?.backendSection).toBe('pipeline');
  expect(entry?.backendPath).toBe(backendPath);
  expect(entry?.type).toBe('number');
  expect(entry?.area).toBe('lab');
  expect(
    Object.prototype.hasOwnProperty.call(BACKEND_DEFAULTS, backendPath),
    `${backendPath} is absent from the backend defaults map — the knob is wired ` +
      'to a path the engine does not serve, or the snapshot is stale',
  ).toBe(true);
  // Assert the COMMITTED SOURCE LITERAL, not `entry.default`. applyBackendDefaults
  // runs at module load and sets `entry.default = BACKEND_DEFAULTS[backendPath]`,
  // so asserting `entry.default` here would be true by construction and could
  // never fail on drift. `offlineDefault` holds the literal from manifest.ts —
  // the value the page actually shows when the snapshot is missing — so this
  // fails if someone edits the literal to something the engine does not use.
  const literal = Object.prototype.hasOwnProperty.call(entry as object, 'offlineDefault')
    ? (entry as SettingsEntry).offlineDefault
    : entry?.default;
  expect(literal, `${id} source literal disagrees with the backend`).toBe(
    BACKEND_DEFAULTS[backendPath],
  );
  return entry as SettingsEntry;
}

