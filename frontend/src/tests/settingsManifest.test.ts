describe('ARCH-05: manifest defaults come from the backend', () => {
  // The duplication itself is the defect. manifest.ts still carries a literal
  // per knob as the OFFLINE fallback, but the value the page uses is overlaid
  // from the backend at load. These tests fail if that overlay stops covering a
  // knob — i.e. if a hardcoded literal starts being what the operator sees.
  const overlaid = SETTINGS_MANIFEST.filter(
    (e) =>
      e.defaultFromBackend !== false &&
      e.backendPath &&
      Object.prototype.hasOwnProperty.call(BACKEND_DEFAULTS, e.backendPath),
  );

  it('the snapshot is populated and covers most of the manifest', () => {
    expect(Object.keys(BACKEND_DEFAULTS).length).toBeGreaterThan(150);
    expect(BACKEND_DEFAULTS_APPLIED).toBeGreaterThan(150);
    expect(overlaid.length).toBe(BACKEND_DEFAULTS_APPLIED);
  });

  it('no overlaid entry disagrees with the backend', () => {
    const drift: string[] = [];
    for (const entry of overlaid) {
      const backendValue = BACKEND_DEFAULTS[entry.backendPath];
      if (entry.default !== backendValue) {
        drift.push(`${entry.id} -> ${entry.backendPath}: ${entry.default} != ${backendValue}`);
      }
    }
    expect(drift, `manifest defaults disagree with the backend:\n  ${drift.join('\n  ')}`).toEqual(
      [],
    );
  });

  it('only the documented %-shaped unit mirrors opt out of the overlay', () => {
    // Each of these renders a fraction-shaped backend rail in whole percent.
    // Overlaying would caption 0.4 under a "%" label. The real fix is to list
    // them in policy._UI_PERCENT_THRESHOLD_PATHS; until then they stay opted out
    // and this test stops the exemption from spreading.
    const optedOut = SETTINGS_MANIFEST.filter((e) => e.defaultFromBackend === false).map((e) => e.id);
    expect(optedOut.sort()).toEqual([
      'pipeline.gauntlet.mc_max_dd_p95',
      'pipeline.robustness_thresholds.param_jitter_pass_rate_min',
      'pipeline.robustness_thresholds.wfa_fold_pass_rate_min',
    ]);
    for (const id of optedOut) {
      const entry = SETTINGS_MANIFEST.find((e) => e.id === id);
      expect(entry?.unit, `${id} opts out of the overlay but is not a %-shaped mirror`).toBe('%');
    }
  });

  it('applyBackendDefaults ignores unknown paths and undefined values', () => {
    const entry: SettingsEntry = {
      id: 'test.entry',
      label: 'Test',
      default: 7,
      type: 'number',
      area: 'system',
      subsection: 'system-telemetry',
      backendSection: 'pipeline',
      backendPath: 'not_a_real_path',
      description: 'test',
      usedBy: ['test'],
    };
    expect(applyBackendDefaults({ other: 1 }, [entry])).toBe(0);
    expect(entry.default).toBe(7);
    expect(applyBackendDefaults({ not_a_real_path: undefined }, [entry])).toBe(0);
    expect(entry.default).toBe(7);
    expect(applyBackendDefaults({ not_a_real_path: 9 }, [entry])).toBe(1);
    expect(entry.default).toBe(9);
  });
});
